/**
 * Тип поля на листе персонажа.
 *  - text: обычное текстовое поле (имя, концепция)
 *  - number: числовое поле (XP, деньги)
 *  - die: выпадающий список d4–d12 (атрибуты, навыки)
 *  - checkbox: галочка (да/нет)
 */
export type FieldType = 'text' | 'number' | 'die' | 'checkbox';

/**
 * Описание одного поля на карте разметки.
 * Координаты и размеры заданы в процентах (0–100) от размеров изображения,
 * чтобы карта работала при любом масштабе.
 */
export interface FieldDefinition {
  /** Уникальный идентификатор. */
  id: string;
  /** Человекочитаемое имя (например, «Ловкость»). */
  name: string;
  /** Тип поля. */
  type: FieldType;
  /** Путь к свойству персонажа (например, "attributes.agility" или "profile.name"). */
  binding: string;
  /** Координата X в процентах от ширины изображения. */
  x: number;
  /** Координата Y в процентах от высоты изображения. */
  y: number;
  /** Ширина в процентах от ширины изображения. */
  width: number;
  /** Высота в процентах от высоты изображения. */
  height: number;
}

/**
 * Карта разметки — описание того, какие поля нарисованы на изображении.
 */
export interface FieldMap {
  /** Уникальный идентификатор карты. */
  id: string;
  /** Имя карты (например, «Стр. 1 — Основное»). */
  name: string;
  /** Изображение в формате data URL (base64). */
  imageDataUrl: string;
  /** Натуральная ширина изображения в пикселях. */
  imageWidth: number;
  /** Натуральная высота изображения в пикселях. */
  imageHeight: number;
  /** Список полей. */
  fields: FieldDefinition[];
}